# Publishes BOTH places of the Otti Colosseum DEV experience straight from the Rojo projects
# (no Studio needed): Rojo builds each place and uploads it through the Open Cloud API.
#
#   .\scripts\publish-places.ps1
#
# The script asks for your Open Cloud API key (typing is hidden; it is not saved anywhere).
# Create the key at create.roblox.com/credentials -> API Keys -> Create API Key:
#   Access permissions: "universe-places" -> experience "10771565873" -> operation "write"
#   (optionally restrict it to your IP address and give it an expiration date)
#
# Note: the upload REPLACES each place with exactly what Rojo builds. Everything in this game is
# generated by scripts at runtime, so nothing is lost - but manual Studio edits to those places
# would be overwritten.
$ErrorActionPreference = "Stop"

$UniverseId = "10771565873"      # Experience ID (DEV)
$HubPlaceId = "127694690386807"  # OTTI HUB (start place)
$ArenaPlaceId = "70661230851944" # COLOSSEUM ARENA

$root = Split-Path -Parent $PSScriptRoot
$rojo = Join-Path $HOME ".aftman\bin\rojo.exe"
if (-not (Test-Path $rojo)) { $rojo = "rojo" }

$secure = Read-Host "Open Cloud API key (input hidden)" -AsSecureString
$bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
try {
    $key = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
    if ([string]::IsNullOrWhiteSpace($key)) { throw "No API key entered." }

    Write-Host "Publishing OTTI HUB ($HubPlaceId)..."
    & $rojo upload (Join-Path $root "places\hub.project.json") --universe_id $UniverseId --asset_id $HubPlaceId --api_key $key
    if ($LASTEXITCODE -ne 0) { throw "Hub upload failed (exit $LASTEXITCODE)." }

    Write-Host "Publishing COLOSSEUM ARENA ($ArenaPlaceId)..."
    & $rojo upload (Join-Path $root "places\arena.project.json") --universe_id $UniverseId --asset_id $ArenaPlaceId --api_key $key
    if ($LASTEXITCODE -ne 0) { throw "Arena upload failed (exit $LASTEXITCODE)." }

    Write-Host "Done: both places are published. New servers use the new version."
}
finally {
    [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)
    $key = $null
}
